# -*- coding: utf-8 -*-
"""从 Basis Set Exchange 生成 K1 格式的基组数据文件 —— **薄封装**。

为什么要有这个脚本：手抄指数与收缩系数是 D-05/D-06 一直开不了工的原因（一次抄错就是静默错）。
BSE 的 Python 包自带全部基组与其出处/修订号，所以把「抄」换成「生成」，
再用 `qwb data sign` 打 sha256、用 `qwb data verify` 校验。

**转录规则不在这里**：`scripts/bse_to_qwb_data.py`（离线 JSON）、
`qwb_studio.datafetch`（按需下载）与本脚本共用
`qwb-studio/qwb_studio/bse_data.py` 这**一份**实现 —— 规则一旦有两份就一定会漂移，
而漂移的后果是静默错数。本脚本只负责「用 `basis_set_exchange` 包取 JSON + 命令行参数」。

用法（需要额外装 `basis_set_exchange`；不用它也能取数，见 `scripts/fetch_data.py`）：

```text
python scripts/gen_basis_from_bse.py def2-TZVP H,C,N,O,F --doi 10.1039/b508541a \\
    --title "Balanced basis sets ..." --url https://www.basissetexchange.org/basis/def2-tzvp/ \\
    --out qwb-data/basis/def2-tzvp.yaml
```

约定（与仓库里已有的基组文件一致，也是 K1 §8.1 的做法）：

* `angular: spherical`、`role: orbital`；
* `normalization: none`（默认）：BSE 导出的收缩系数**不重新归一化**，由 loader 在加载时
  归一化一次。（对本来已归一化的基组是空操作；对 Turbomole 约定的 def2 系列是必要的。）
  STO-3G 这类"导出时已按 l² 归一"的基组用 `--normalization l2`。
* `contraction_type`：逐壳层判定 —— 一个壳层只有一组系数 → `segmented`，多组 → `general`。
* sha256 不在这里写，交给 `qwb data sign`（数据文件是工具产物）。
"""

from __future__ import annotations

import argparse
import io
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "qwb-studio"))

from qwb_studio.bse_data import (  # noqa: E402 - 需要先改 sys.path
    TranscriptionError,
    transcribe_basis,
)

try:  # 只有这个脚本需要 BSE 的 Python 包；其余取数路径只依赖标准库。
    import basis_set_exchange as bse
except ImportError:  # pragma: no cover - 取决于本机环境
    bse = None  # type: ignore[assignment]


def spec_from_args(args: argparse.Namespace, revision: str) -> dict:
    """命令行参数 → `transcribe_basis` 的 `spec`（与 `sources.json` 的 `transcribe` 同形）。"""
    notes = (
        "Generated by scripts/gen_basis_from_bse.py from Basis Set Exchange "
        "(revision: {rev}); never transcribed by hand. Declared normalization={norm} "
        "on purpose: the exported contraction coefficients are not renormalized, so the "
        "loader normalizes once at load time (project.md 8.1)."
    ).format(rev=revision, norm=args.normalization)
    return {
        "name": args.basis.lower(),
        "version": "1.0.0",
        "notes": notes,
        "citations": [{"title": args.title, "doi": args.doi, "url": args.url}],
        "license": {"spdx": "Apache-2.0", "commercial_ok": True, "redistribute_ok": True},
        "created": "2026-10-25T00:00:00Z",
        "angular": "spherical",
        "normalization": args.normalization,
        "role": "orbital",
    }


def count_functions(text: str) -> int:
    """数生成文件里的球谐函数个数（Σ(2l+1)）—— 纯文本扫，不依赖 YAML 解析器。"""
    total = 0
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("- l: "):
            total += 2 * int(stripped[len("- l: ") :]) + 1
    return total


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("basis")
    parser.add_argument("elements", help="逗号分隔，例如 H,C,N,O")
    parser.add_argument("--doi", required=True)
    parser.add_argument("--title", required=True)
    parser.add_argument("--url", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument(
        "--normalization",
        default="none",
        choices=["none", "l2"],
        help="none（默认，BSE 原样系数）/ l2（导出已归一，如 STO-3G）",
    )
    parser.add_argument("--check-against", help="与已有文件对比（自检转换器）")
    arguments = parser.parse_args()

    if bse is None:
        print(
            "需要 basis_set_exchange 包（pip install basis_set_exchange）；"
            "不想装它就用 python scripts/fetch_data.py --need <path>",
            file=sys.stderr,
        )
        return 1

    elements = [item.strip() for item in arguments.elements.split(",") if item.strip()]
    data = bse.get_basis(arguments.basis, elements=elements)
    revision = data.get("revision_description", "")

    try:
        text = transcribe_basis(spec_from_args(arguments, revision), data)
    except TranscriptionError as error:
        print(f"转录失败：{error}", file=sys.stderr)
        return 1
    io.open(arguments.out, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote {} ({} 元素, 修订: {})".format(arguments.out, len(elements), revision))

    # 自检：按 BSE 的 l 列表算期望的球谐函数数，再与生成文件里 Σ(2l+1) 比。
    expected = 0
    for entry in data["elements"].values():
        for shell in entry["electron_shells"]:
            expected += sum(2 * l + 1 for l in shell["angular_momentum"])
    produced = count_functions(text)
    if produced != expected:
        print(
            "函数数自检失败：期望 {} 个球谐函数，生成文件里是 {}".format(expected, produced),
            file=sys.stderr,
        )
        return 1
    print("  函数数自检：{} 个球谐函数（与 BSE 的 l 列表一致）".format(produced))

    if arguments.check_against:
        try:
            import yaml
        except ImportError:
            print("  （跳过 --check-against：需要 PyYAML，pip install pyyaml）", file=sys.stderr)
            return 0
        generated = yaml.safe_load(text)
        existing = yaml.safe_load(io.open(arguments.check_against, encoding="utf-8"))
        worst_exponent = 0.0
        worst_coefficient = 0.0
        compared = 0
        for entry in generated["shells"]:
            symbol = entry["element"]
            match = [e for e in existing["shells"] if e["element"] == symbol]
            if not match:
                print("  已有文件缺元素", symbol)
                continue
            for new_shell, old_shell in zip(entry["shells"], match[0]["shells"]):
                if new_shell["l"] != old_shell["l"]:
                    print("  {} 的 l 顺序不同".format(symbol))
                    continue
                for a, b in zip(new_shell["exponents"], old_shell["exponents"]):
                    worst_exponent = max(worst_exponent, abs(a - b))
                    compared += 1
                for new_array, old_array in zip(
                    new_shell["coefficients"], old_shell["coefficients"]
                ):
                    for a, b in zip(new_array, old_array):
                        worst_coefficient = max(worst_coefficient, abs(a - b))
        print(
            "  自检：对比 {} 个指数，最大指数差 {:.2e}，最大系数差 {:.2e}".format(
                compared, worst_exponent, worst_coefficient
            )
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
