# -*- coding: utf-8 -*-
"""从 Basis Set Exchange 生成 K1 格式的基组数据文件。

为什么要有这个脚本：手抄指数与收缩系数是 D-05/D-06 一直开不了工的原因（一次抄错就是静默错）。
BSE 的 Python 包自带全部基组与其出处/修订号，所以把「抄」换成「生成」，
再用 `qwb-stamp-data` 打 sha256、用 `qwb data verify` 校验。

用法：

```text
python scripts/gen_basis_from_bse.py def2-TZVP H,C,N,O,F --doi 10.1039/b508541a \
    --title "Balanced basis sets ..." --url https://www.basissetexchange.org/basis/def2-tzvp/ \
    --out qwb-data/basis/def2-tzvp.yaml
```

约定（与已有的 `def2-svp.yaml` 一致，也是 K1 §8.1 的做法）：

* `angular: spherical`、`role: orbital`；
* `normalization: none`：BSE 导出的收缩系数**不重新归一化**，由 loader 在加载时归一化一次。
  （对本来已归一化的基组如 cc-pVDZ 这是个空操作；对 Turbomole 约定的 def2 系列则是必要的。）
* `contraction_type`：每个壳层只有一组系数 → `segmented`；多组 → `general`。
* sha256 不在这里写，交给 `qwb-stamp-data`（数据文件是工具产物，注释会被丢弃）。
"""

from __future__ import annotations

import argparse
import io

import basis_set_exchange as bse

HEADER = """\
name: {name}
version: 1.0.0
notes: '{notes}'
citation:
- title: {title}
  doi: {doi}
  url: {url}
license:
  spdx: Apache-2.0
  commercial_ok: true
  redistribute_ok: true
created: {created}
elements:
{elements}
angular: spherical
normalization: none
role: orbital
shells:
"""


def element_symbols(numbers) -> list[str]:
    table = {}
    for symbol in (
        "H He Li Be B C N O F Ne Na Mg Al Si P S Cl Ar K Ca Sc Ti V Cr Mn Fe Co Ni "
        "Cu Zn Ga Ge As Se Br Kr"
    ).split():
        table.setdefault(len(table) + 1, symbol)
    return [table[int(n)] for n in numbers]


def render(name: str, elements: list[str], title: str, doi: str, url: str, revision: str) -> str:
    data = bse.get_basis(name, elements=elements)
    notes = (
        "Generated by scripts/gen_basis_from_bse.py from Basis Set Exchange "
        "(revision: {rev}); never transcribed by hand. Declared normalization=none "
        "on purpose: the exported contraction coefficients are not renormalized, so the "
        "loader normalizes once at load time (project.md 8.1)."
    ).format(rev=revision)
    created = "2026-10-25T00:00:00Z"
    text = HEADER.format(
        name=name.lower(),
        notes=notes,
        title=title,
        doi=doi,
        url=url,
        created=created,
        elements="\n".join("- {}".format(symbol) for symbol in elements),
    )
    symbols = element_symbols(data["elements"].keys())
    for symbol, number in zip(symbols, data["elements"]):
        # K1 的语义检查要求壳层按 l 升序（BSE 的 6-311G(d,p) 是 s,s,s,d,s,p… 的顺序）。
        # 排序是**稳定的**，同一 l 内的相对顺序保持不变。
        shells = []
        for shell in data["elements"][number]["electron_shells"]:
            angulars = shell["angular_momentum"]
            coefficients = shell["coefficients"]
            if len(angulars) > 1:
                # BSE 的「sp 复合壳层」：每个 l 配一个系数数组（6-311G(d,p) 的 O 就是这种）。
                # 早期实现给每个 l 都写了全部数组，于是把 30 个函数撑成 42 个，
                # 顺带让 S 矩阵近线性相关（42 个方向里 8 个本征值 ~1e-16）。
                if len(coefficients) != len(angulars):
                    raise SystemExit(
                        "复合壳层的 l 数与系数数组数不等 ({} vs {})，BSE 约定不明，拒绝生成".format(
                            len(angulars), len(coefficients)
                        )
                    )
                for angular, array in zip(angulars, coefficients):
                    shells.append((angular, shell["exponents"], [array], "segmented"))
            else:
                contraction_type = "segmented" if len(coefficients) == 1 else "general"
                shells.append((angulars[0], shell["exponents"], coefficients, contraction_type))
        shells.sort(key=lambda item: item[0])
        text += "- element: {}\n  shells:\n".format(symbol)
        for angular, exponents, coefficients, contraction_type in shells:
            text += "  - l: {}\n".format(angular)
            text += "    exponents:\n"
            for exponent in exponents:
                text += "    - {}\n".format(float(exponent))
            text += "    coefficients:\n"
            for array in coefficients:
                text += "    -\n"
                for value in array:
                    text += "      - {}\n".format(float(value))
            text += "    contraction_type: {}\n".format(contraction_type)
    return text


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("basis")
    parser.add_argument("elements", help="逗号分隔，例如 H,C,N,O")
    parser.add_argument("--doi", required=True)
    parser.add_argument("--title", required=True)
    parser.add_argument("--url", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--check-against", help="与已有文件对比（自检转换器）")
    arguments = parser.parse_args()

    elements = [item.strip() for item in arguments.elements.split(",") if item.strip()]
    data = bse.get_basis(arguments.basis, elements=elements)
    revision = data.get("revision_description", "")
    text = render(
        arguments.basis,
        elements,
        arguments.title,
        arguments.doi,
        arguments.url,
        revision,
    )
    io.open(arguments.out, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote {} ({} 元素, 修订: {})".format(arguments.out, len(elements), revision))

    # 自检：按 BSE 的 l 列表算期望的球谐函数数，再与生成文件里 Σ(2l+1) 比。
    expected = 0
    for entry in data["elements"].values():
        for shell in entry["electron_shells"]:
            expected += sum(2 * l + 1 for l in shell["angular_momentum"])
    import yaml as _yaml

    produced = 0
    for entry in _yaml.safe_load(text)["shells"]:
        for shell in entry["shells"]:
            produced += 2 * shell["l"] + 1
    if produced != expected:
        raise SystemExit(
            "函数数自检失败：期望 {} 个球谐函数，生成文件里是 {} 个".format(expected, produced)
        )
    print("  函数数自检：{} 个球谐函数（与 BSE 的 l 列表一致）".format(produced))

    if arguments.check_against:
        import yaml

        generated = yaml.safe_load(text)
        existing = yaml.safe_load(io.open(arguments.check_against, encoding="utf-8"))
        worst_exponent = 0.0
        worst_coefficient = 0.0
        compared = 0
        for entry in generated["shells"]:
            symbol = entry["element"]
            match = [e for e in existing["shells"] if e["element"] == symbol]
            if not match:
                print("  已有文件缺元素", symbol)
                continue
            for new_shell, old_shell in zip(entry["shells"], match[0]["shells"]):
                if new_shell["l"] != old_shell["l"]:
                    print("  {} 的 l 顺序不同".format(symbol))
                    continue
                for a, b in zip(new_shell["exponents"], old_shell["exponents"]):
                    worst_exponent = max(worst_exponent, abs(a - b))
                    compared += 1
                for new_array, old_array in zip(
                    new_shell["coefficients"], old_shell["coefficients"]
                ):
                    for a, b in zip(new_array, old_array):
                        worst_coefficient = max(worst_coefficient, abs(a - b))
        print(
            "  自检：对比 {} 个指数，最大指数差 {:.2e}，最大系数差 {:.2e}".format(
                compared, worst_exponent, worst_coefficient
            )
        )


if __name__ == "__main__":
    main()
