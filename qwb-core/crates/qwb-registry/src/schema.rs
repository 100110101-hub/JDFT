//! K1 schema 生成（C-01 定案：`schemars` 从 Rust 类型生成）。
//!
//! 因为 Rust 类型是唯一真相源，`qwb-contracts/schema/*.schema.json` 不可能与代码漂移：
//! CI 跑 `qwb-gen-schemas --check`，任何差异都会失败。

use schemars::schema_for;

use crate::basis::BasisSet;
use crate::ecp::Ecp;
use crate::functional::Functional;
use crate::grid::GridLevelDef;
use crate::molecule::MoleculeFile;
use crate::numerics::NumericsDef;
use crate::registry::RegistryManifest;
use crate::solvent::Solvent;
use crate::verify::DataKind;

/// 生成一个类别的 JSON Schema。
#[must_use]
pub fn schema_for_kind(kind: DataKind) -> schemars::Schema {
    match kind {
        DataKind::Basis => schema_for!(BasisSet),
        DataKind::Ecp => schema_for!(Ecp),
        DataKind::Functional => schema_for!(Functional),
        DataKind::Grid => schema_for!(GridLevelDef),
        DataKind::Solvent => schema_for!(Solvent),
        DataKind::Numerics => schema_for!(NumericsDef),
        DataKind::Molecule => schema_for!(MoleculeFile),
        DataKind::Registry => schema_for!(RegistryManifest),
    }
}

/// 全部类别的 schema，顺序同 [`DataKind::ALL`]。
#[must_use]
pub fn all() -> Vec<(DataKind, schemars::Schema)> {
    DataKind::ALL
        .into_iter()
        .map(|kind| (kind, schema_for_kind(kind)))
        .collect()
}

/// 渲染为格式稳定的 JSON（2 空格缩进 + 结尾换行）。
///
/// # Errors
///
/// schema 序列化失败（不应发生）。
pub fn to_json(schema: &schemars::Schema) -> Result<String, serde_json::Error> {
    let mut text = serde_json::to_string_pretty(schema)?;
    text.push('\n');
    Ok(text)
}

/// 渲染为 YAML（K1 要求 `*.schema.yaml`，与 JSON 内容等价：JSON 是 YAML 1.2 子集，
/// 这里用 YAML 序列化保证人可读）。
///
/// # Errors
///
/// 转换失败。
pub fn to_yaml(schema: &schemars::Schema) -> Result<String, String> {
    let json = serde_json::to_value(schema).map_err(|e| e.to_string())?;
    let body = serde_yaml::to_string(&json).map_err(|e| e.to_string())?;
    Ok(format!("{HEADER}{body}"))
}

/// 生成文件头的固定文本（`--check` 也逐字节比较它）。
pub const HEADER: &str = "# GENERATED by qwb-gen-schemas from qwb-registry Rust types. DO NOT EDIT.\n# Source of truth: qwb-core/crates/qwb-registry/src/*.rs (K1)\n";

#[cfg(test)]
mod tests {
    use super::{HEADER, all, to_json, to_yaml};
    use crate::verify::DataKind;

    /// K1 的共同字段。5 个数据类型里是**复制粘贴**的（Rust 的 macro_rules! 不能出现在
    /// struct 字段位置），所以由这个测试保证它们不会漂移。
    const COMMON: [&str; 7] = [
        "name", "version", "citation", "license", "created", "sha256", "notes",
    ];

    /// 有共同字段的数据类别（分子是用户输入，注册表是索引，都不算 G2 数据集）。
    fn data_kinds() -> Vec<DataKind> {
        vec![
            DataKind::Basis,
            DataKind::Ecp,
            DataKind::Functional,
            DataKind::Grid,
            DataKind::Solvent,
            DataKind::Numerics,
        ]
    }

    fn properties(kind: DataKind) -> serde_json::Value {
        let json = to_json(&super::schema_for_kind(kind)).expect("json");
        let value: serde_json::Value = serde_json::from_str(&json).expect("parse");
        value
            .get("properties")
            .cloned()
            .unwrap_or_else(|| panic!("{} schema has no properties", kind.dir_name()))
    }

    #[test]
    fn every_kind_has_a_schema() {
        let schemas = all();
        assert_eq!(schemas.len(), DataKind::ALL.len());
        for (kind, schema) in schemas {
            let json = to_json(&schema).expect("json");
            assert!(
                json.contains("\"$schema\""),
                "{} schema lacks $schema",
                kind.dir_name()
            );
            let yaml = to_yaml(&schema).expect("yaml");
            assert!(yaml.starts_with(HEADER));
            assert!(yaml.contains("type: object"));
        }
    }

    #[test]
    fn common_fields_are_identical_across_kinds() {
        let reference = properties(DataKind::Basis);
        for kind in data_kinds() {
            let props = properties(kind);
            for field in COMMON {
                let expected = reference
                    .get(field)
                    .unwrap_or_else(|| panic!("basis schema lacks {field}"));
                let actual = props
                    .get(field)
                    .unwrap_or_else(|| panic!("{} schema lacks {field}", kind.dir_name()));
                assert_eq!(
                    serde_json::to_string(actual).expect("json"),
                    serde_json::to_string(expected).expect("json"),
                    "{} field `{field}` drifted from BasisSet's definition",
                    kind.dir_name()
                );
            }
        }
    }

    #[test]
    fn citation_and_license_are_required_by_the_schema() {
        // K1: citation/license 是 required；缺失必须在 schema 层被拒（G2 的第一道门）。
        for kind in data_kinds() {
            let json = to_json(&super::schema_for_kind(kind)).expect("json");
            let value: serde_json::Value = serde_json::from_str(&json).expect("parse");
            let required: Vec<String> = value
                .get("required")
                .and_then(|r| r.as_array())
                .map(|a| {
                    a.iter()
                        .filter_map(|v| v.as_str().map(ToString::to_string))
                        .collect()
                })
                .unwrap_or_default();
            for field in ["name", "version", "citation", "license", "created"] {
                assert!(
                    required.contains(&field.to_string()),
                    "{}: `{field}` must be required",
                    kind.dir_name()
                );
            }
            // sha256/notes 是工具生成/可选的，不能 required。
            for field in ["sha256", "notes"] {
                assert!(
                    !required.contains(&field.to_string()),
                    "{}: `{field}` must be optional",
                    kind.dir_name()
                );
            }
        }
    }

    #[test]
    fn deny_unknown_fields_becomes_additional_properties_false() {
        // serde 的 deny_unknown_fields 必须体现在 schema 里，否则 K1 与代码不等价。
        let json = to_json(&super::schema_for_kind(DataKind::Basis)).expect("json");
        assert!(
            json.contains("\"additionalProperties\": false"),
            "schema must forbid unknown properties: {json}"
        );
    }

    #[test]
    fn required_fields_are_declared() {
        let json = to_json(&super::schema_for_kind(DataKind::Basis)).expect("json");
        for field in ["citation", "license", "elements", "angular", "shells"] {
            assert!(json.contains(&format!("\"{field}\"")), "missing {field}");
        }
    }
}
